import fs from 'node:fs';
import path from 'node:path';
import { validateContextState } from '../context/validator.js';
import { validateContextManifest } from '../schemas/context-schema.js';
import { BRAIN_DIR } from './renderer.js';

// Context Packages — a metadata-only projection of the Context Compiler's
// state (`.ddae/context/`) into the Project Brain. This is a second,
// independent view producer (contrato B.1), never part of Brain Manifest
// v1 and never a second Context Compiler:
//
//   .ddae/context/{manifest.json, validation.json}  (existing, read-only)
//        │
//        ▼  collectContextPackageState — the only I/O boundary
//   Safe State (metadata only, never file content, never goal text)
//        │
//        ▼  renderContextPackagesView — pure
//   { path: 'DDAE-Brain/Context-Packages.md', content }
//
// `src/context/**` is only imported (`validateContextState`,
// `validateContextManifest`), never reimplemented or modified — this
// module never runs its own freshness algorithm.
//
// Bloco 06, Decisão D3 / Bloco 08, D2: this view links back to Home; Home
// links here only because the Orchestrator declares this path in
// `manifest.views` (the Renderer derives its navigation from the Manifest and
// never imports this module).

export const CONTEXT_PACKAGES_VIEW_PATH = `${BRAIN_DIR}/Context-Packages.md`;

const MARKER = '_Generated by DDAE. Derived from Docs/ and Git. Do not edit directly._';
const HOME_LINK = '[Home](./Home.md)';

const EMPTY_STATE = Object.freeze({
  availability: 'missing',
  status: null,
  reasons: Object.freeze([]),
  schema_version: null,
  engine_version: null,
  goal_hash: null,
  budget: null,
  fingerprint: null,
  counts: null,
  relevant_files: Object.freeze([]),
});

function contextDir(root) {
  return path.join(root, '.ddae', 'context');
}

function readJsonFile(absPath) {
  if (!fs.existsSync(absPath)) {
    return { present: false, value: undefined, error: null };
  }
  let raw;
  try {
    raw = fs.readFileSync(absPath, 'utf8');
  } catch {
    return { present: true, value: undefined, error: 'READ_FAILED' };
  }
  try {
    return { present: true, value: JSON.parse(raw), error: null };
  } catch {
    return { present: true, value: undefined, error: 'PARSE_FAILED' };
  }
}

function corrupt(reasonCode) {
  return { ...EMPTY_STATE, availability: 'present', status: 'CORRUPT', reasons: Object.freeze([{ code: reasonCode }]) };
}

/** Reduces a full (schema-valid) Context Manifest v1 to the metadata-only Safe State — never content, never goal text. */
function toSafeState(manifest, status, reasons) {
  return Object.freeze({
    availability: 'present',
    status,
    reasons: Object.freeze(reasons.map((reason) => Object.freeze({ ...reason }))),
    schema_version: manifest.schema_version,
    engine_version: manifest.compiler?.engine_version ?? null,
    goal_hash: manifest.goal?.hash ?? null,
    budget: Object.freeze({ profile: manifest.budget.profile, max_chars: manifest.budget.max_chars }),
    fingerprint: Object.freeze({ algorithm: manifest.fingerprint.algorithm, value: manifest.fingerprint.value }),
    counts: Object.freeze({
      sources: manifest.sources.length,
      relevant_files: manifest.relevant_files.length,
      excluded_sources: manifest.excluded_sources.length,
    }),
    relevant_files: Object.freeze(
      manifest.relevant_files.map((entry) => Object.freeze({ path: entry.path ?? null, score: entry.score, char_cost: entry.char_cost })),
    ),
  });
}

/**
 * Collects the current, safe, metadata-only state of the Context Compiler's
 * output for `projectRoot`. Read-only: never writes, never re-reads project
 * file content (the Sensitive Data Guard is not re-invoked here —
 * `currentSourceHashes` is intentionally omitted from `validateContextState`,
 * so a manifest with `relevant_files` always degrades to STALE/
 * SOURCE_FRESHNESS_UNVERIFIED rather than a false VALID). Degrades to a
 * deterministic state for every expected condition (missing, corrupt,
 * partial) — never throws for those; only a genuinely invalid `projectRoot`
 * throws (programmer error, same policy as `discoverWorkspaceState`).
 *
 * `options.currentGitContext` / `options.currentDdaeContext` (Bloco 08, D4)
 * are optional current-state snapshots the caller — the Orchestrator's I/O
 * boundary — already collected with the existing Context Compiler
 * collectors. They are only forwarded to `validateContextState`, which
 * already knows how to use them; omitting them keeps the Bloco 06 behaviour
 * exactly. No `currentSourceHashes` is ever computed here.
 */
export function collectContextPackageState(projectRoot, options = {}) {
  const { currentGitContext = null, currentDdaeContext = null } = options ?? {};
  const root = path.resolve(projectRoot);
  if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
    throw new Error(`collectContextPackageState: projectRoot does not exist or is not a directory: ${root}`);
  }

  const dir = contextDir(root);
  const manifestFile = readJsonFile(path.join(dir, 'manifest.json'));
  if (!manifestFile.present) {
    return EMPTY_STATE;
  }
  if (manifestFile.error) {
    return corrupt('MANIFEST_JSON_INVALID');
  }

  const manifest = manifestFile.value;
  const schemaCheck = validateContextManifest(manifest);
  if (!schemaCheck.valid) {
    return corrupt('MANIFEST_SCHEMA_INVALID');
  }

  const validationFile = readJsonFile(path.join(dir, 'validation.json'));
  const contextMdExists = fs.existsSync(path.join(dir, 'CONTEXT.md'));

  // validateContextState is reused as-is (never reimplemented). Git/DDAE
  // context are used only when the caller supplied them (Bloco 08, D4);
  // without them the git/session staleness checks are skipped (never a false
  // STALE for those). `currentSourceHashes` is deliberately never supplied,
  // so `SOURCE_FRESHNESS_UNVERIFIED` still fires whenever there are
  // relevant_files — never a false VALID.
  const { status, reasons } = validateContextState({
    manifest,
    contextMarkdown: contextMdExists ? undefined : undefined,
    currentGitContext,
    currentDdaeContext,
  });
  void validationFile; // present only informatively; the receipt is never trusted blindly (Seção 7 of the block)

  return toSafeState(manifest, status, reasons);
}

function code(value) {
  const text = String(value ?? '');
  const longestRun = (text.match(/`+/g) ?? []).reduce((max, run) => Math.max(max, run.length), 0);
  const fence = '`'.repeat(longestRun + 1);
  const needsPadding = text === '' || text.startsWith('`') || text.endsWith('`');
  return needsPadding ? `${fence} ${text} ${fence}` : `${fence}${text}${fence}`;
}

function renderStatusSection(state) {
  if (state.availability === 'missing') {
    return [
      '## Status',
      '',
      'No Context Package is currently available.',
      '',
      'Run `ddae-engine context build --goal "<text>"` to create one.',
    ].join('\n');
  }
  const lines = [
    '## Status',
    '',
    `- Status: ${code(state.status)}`,
    `- Schema: ${code(state.schema_version)}`,
    `- Engine: ${code(state.engine_version)}`,
  ];
  if (state.goal_hash !== null) {
    lines.push(`- Goal hash: ${code(state.goal_hash)}`);
  }
  if (state.budget !== null) {
    lines.push(`- Budget: ${code(state.budget.profile)} (max ${state.budget.max_chars} chars)`);
  }
  if (state.fingerprint !== null) {
    lines.push(`- Fingerprint (${state.fingerprint.algorithm}): ${code(state.fingerprint.value)}`);
  }
  if (state.counts !== null) {
    lines.push(`- Sources: ${state.counts.sources}`, `- Relevant files: ${state.counts.relevant_files}`, `- Excluded sources: ${state.counts.excluded_sources}`);
  }
  if (state.reasons.length > 0) {
    lines.push('', '### Reasons', '', ...state.reasons.map((reason) => `- ${code(JSON.stringify(reason))}`));
  }
  return lines.join('\n');
}

function renderImportantFilesSection(state) {
  const lines = ['## Important Files', ''];
  if (state.relevant_files.length === 0) {
    lines.push('No relevant files recorded.');
    return lines.join('\n');
  }
  for (const entry of state.relevant_files) {
    lines.push(`- ${code(entry.path)} — score: ${entry.score}, char cost: ${entry.char_cost}`);
  }
  return lines.join('\n');
}

/**
 * Renders a Context Package Safe State into the Context Packages view — a
 * pure function: no filesystem, no network, no clock, no randomness, no
 * Git/Docs collector, no Claude-Mem. Same state → the same bytes.
 */
export function renderContextPackagesView(state) {
  const content = [
    '# Context Packages',
    MARKER,
    renderStatusSection(state),
    renderImportantFilesSection(state),
    HOME_LINK,
  ].join('\n\n');
  return Object.freeze({ path: CONTEXT_PACKAGES_VIEW_PATH, content: `${content}\n` });
}
