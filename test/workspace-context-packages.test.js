const MARKER = '_Generated by DDAE. Derived from Docs/ and Git. Do not edit directly._';
const SECRET_CONTENT = 'SUPER_SECRET_CONTENT_123';
const SECRET_GOAL_TEXT = 'PRIVATE_GOAL_TEXT_456';
const SECRET_GOAL_NORMALIZED = 'normalized_private_goal_789';

function gitFixture(overrides = {}) {
  return {
    available: true,
    repository: true,
    branch: 'main',
    head: 'a'.repeat(40),
    working_tree: 'clean',
    modified_files: [],
    untracked_files: [],
    recent_commits: [],
    tags: [],
    warnings: [],
    ...overrides,
  };
}

function ddaeFixture(overrides = {}) {
  return {
    available: true,
    current_session: { name: 'session_06_x', path: 'Docs/05_sessions/session_06_x' },
    selection: { requested: null, selected: 'session_06_x', reason: 'latest_canonical' },
    ...overrides,
  };
}

function candidateWithContent(idSeed, content, extra = {}) {
  const source = createSource({ kind: 'documentation', domain: 'history', identity: idSeed, content, ...extra });
  return { source, content, signals: extra.signals };
}

/** A real, schema-valid Context Manifest v1 — built with the actual compiler, never hand-typed. */
function buildManifest(overrides = {}) {
  return compileContext({
    engineVersion: '0.3.0',
    project: { name: 'demo', root_kind: 'ddae' },
    goal: SECRET_GOAL_TEXT,
    gitContext: gitFixture(),
    ddaeContext: ddaeFixture(),
    candidates: [candidateWithContent('doc_a', SECRET_CONTENT, { path: 'Docs/a.md' })],
    ...overrides,
  });
}

function write(root, rel, content) {
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, 'utf8');
}

function contextDir(root) {
  return path.join(root, '.ddae', 'context');
}

function writeManifest(root, manifest) {
  write(root, '.ddae/context/manifest.json', `${stableStringify(manifest)}\n`);
}

function writeValidation(root, receipt) {
  write(root, '.ddae/context/validation.json', `${stableStringify(receipt)}\n`);
}

function buildValidationReceipt(manifest, status = 'VALID', reasons = []) {
  return { schema_version: manifest.schema_version, status, fingerprint: manifest.fingerprint.value, reasons };
}

