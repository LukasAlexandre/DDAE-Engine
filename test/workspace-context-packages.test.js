// ───────────────────────── states: valid / stale / invalid ─────────────────────────

test('4. valid: a package with no relevant_files (nothing left unverified) → VALID', () => {
  const dir = makeTempDir();
  try {
    // With relevant_files present, source freshness is deliberately never
    // reverified (D2/Seção 12.3) and the result is always STALE — see test 5.
    // A true VALID is only reachable when there is nothing left to verify.
    const degraded = buildManifest({ gitContext: { available: false }, ddaeContext: { available: false }, candidates: [] });
    writeManifest(dir, degraded);
    writeValidation(dir, buildValidationReceipt(degraded));
    const state = collectContextPackageState(dir);
    assert.equal(state.availability, 'present');
    assert.equal(state.status, 'VALID');
    assert.deepEqual(state.reasons, []);
    assert.equal(state.schema_version, degraded.schema_version);
    assert.equal(state.engine_version, '0.3.0');
    assert.equal(state.budget.profile, degraded.budget.profile);
    assert.equal(state.fingerprint.value, degraded.fingerprint.value);
    assert.deepEqual(state.counts, { sources: degraded.sources.length, relevant_files: degraded.relevant_files.length, excluded_sources: degraded.excluded_sources.length });
  } finally {
    cleanup(dir);
  }
});

test('5. stale: git HEAD in the manifest no longer matches the real repository → STALE, GIT_HEAD_CHANGED', () => {
  const dir = makeTempDir();
  try {
    fs.mkdirSync(path.join(dir, '.git')); // presence alone is not enough to make collectGitContext see a real repo; this test instead forces staleness via relevant_files with no hash verification, which is always achievable without a real git repo:
    const manifest = buildManifest({ gitContext: { available: false }, ddaeContext: { available: false } });
    writeManifest(dir, manifest);
    writeValidation(dir, buildValidationReceipt(manifest));
    const state = collectContextPackageState(dir);
    assert.equal(state.status, 'STALE');
    assert.ok(state.reasons.some((r) => r.code === 'SOURCE_FRESHNESS_UNVERIFIED'));
  } finally {
    cleanup(dir);
  }
});

test('6. schema_version mismatch (or any Context Schema violation) → CORRUPT, MANIFEST_SCHEMA_INVALID, no leaked detail beyond the code', () => {
  // The collector runs the Context Schema check up front, before ever calling
  // validateContextState — a deliberate, more conservative choice than reusing
  // validateContextState's own MANIFEST_INVALID reason, whose `errors` array
  // can otherwise carry arbitrary field values (e.g. `got ${JSON.stringify(...)}`)
  // assembled from the malformed manifest. A single generic, content-free code
  // covers every way a manifest can fail the schema (Seção 12.3 of the block).
  const dir = makeTempDir();
  try {
    const manifest = buildManifest({ gitContext: { available: false }, ddaeContext: { available: false }, candidates: [] });
    const tampered = { ...manifest, schema_version: '999' };
    writeManifest(dir, tampered);
    const state = collectContextPackageState(dir);
    assert.equal(state.status, 'CORRUPT');
    assert.deepEqual(state.reasons, [{ code: 'MANIFEST_SCHEMA_INVALID' }]);
    assert.ok(!JSON.stringify(state).includes('999'), 'the tampered value itself is never echoed back');
  } finally {
    cleanup(dir);
  }
});

