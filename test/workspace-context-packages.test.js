const readCode = (...segments) => fs.readFileSync(path.join(REPO_ROOT, ...segments), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '');

test('22. renderContextPackagesView is pure: no fs/network/clock/randomness/Git/Docs/Claude-Mem, imports only the schema-free minimum', () => {
  const code = readCode('src', 'workspace', 'context-packages.js');
  for (const token of ['fetch(', 'node:http', 'node:https', 'node:net', 'node:child_process', 'Date.now', 'new Date', 'Math.random', 'randomUUID', 'collectGitContext', 'collectDdaeContext', 'compileContext', 'renderContextMarkdown']) {
    assert.ok(!code.includes(token), `context-packages.js must not reference ${token}`);
  }
  const lower = code.toLowerCase();
  assert.ok(!lower.includes('claude-mem') && !lower.includes('memoryprovider'));
});

test('23. the collector is the only I/O boundary: no filesystem write ever happens, in any state', () => {
  const dir = makeTempDir();
  try {
    write(dir, 'package.json', '{}');
    const list = () => fs.readdirSync(dir, { recursive: true }).sort();
    const before = list();
    const manifest = buildManifest({ gitContext: { available: false }, ddaeContext: { available: false } });
    writeManifest(dir, manifest);
    writeValidation(dir, buildValidationReceipt(manifest));
    const listAfterWrite = list();
    const state = collectContextPackageState(dir);
    renderContextPackagesView(state);
    assert.deepEqual(list(), listAfterWrite);
    assert.ok(!fs.existsSync(path.join(dir, 'DDAE-Brain')));
  } finally {
    cleanup(dir);
  }
});

