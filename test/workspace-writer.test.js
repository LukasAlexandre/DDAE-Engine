// Platforms/users that cannot create file symlinks (S4/S5 skip there) still exercise the same
// decision through a simulated lstat — a real file that lstat reports as a symbolic link.
function withSimulatedFileSymlink(suffix, fn) {
  const restore = patchFs('lstatSync', (real) => (target, ...rest) => {
    const stat = real(target, ...rest);
    if (String(target).endsWith(suffix)) {
      return { isSymbolicLink: () => true, isFile: () => false, isDirectory: () => false, size: stat.size };
    }
    return stat;
  });
  try {
    return fn();
  } finally {
    restore();
  }
}

test('S4b. (simulated lstat) a view target reported as a symlink is SYMLINK_REFUSED, also with force, and nothing is written', () => {
  withProject(({ root }) => {
    writeBrainWorkspace(root, smallPlan());
    const before = tree(root).map((entry) => (entry.endsWith('/') ? entry : `${entry}=${read(root, entry)}`));
    for (const force of [false, true]) {
      const error = withSimulatedFileSymlink('Home.md', () => errorOf(() => writeBrainWorkspace(root, { manifest: { ...SMALL_MANIFEST, note: 'v2' }, files: [file('Home.md', 'v2\n'), file('Sessions.md', 'v2\n')] }, { force })));
      assert.equal(error.code, 'SYMLINK_REFUSED');
      assert.equal(error.details.path, 'DDAE-Brain/Home.md');
    }
    assert.deepEqual(tree(root).map((entry) => (entry.endsWith('/') ? entry : `${entry}=${read(root, entry)}`)), before);
  });
});

