    const restoreRename = patchFs('renameSync', (real) => (...args) => { calls.push(['rename', ...args]); return real(...args); });
    const restoreOpen = patchFs('openSync', (real) => (...args) => { if (/[wa]/.test(String(args[1] ?? 'r'))) calls.push(['open', args[0]]); return real(...args); });
