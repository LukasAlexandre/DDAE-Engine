/** outer/{project,outside}; `outside` holds a sentinel that must never change. */
function makeProject() {
  const outer = fs.mkdtempSync(path.join(os.tmpdir(), 'ddae-writer-test-'));
  const root = path.join(outer, 'project');
  const outside = path.join(outer, 'outside');
  fs.mkdirSync(root);
  fs.mkdirSync(outside);
  fs.writeFileSync(path.join(outside, 'sentinel.txt'), 'untouched', 'utf8');
  return { outer, root, outside };
}

function withProject(fn) {
  const project = makeProject();
  try {
    return fn(project);
  } finally {
    cleanup(project.outer);
  }
}

function tree(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const abs = path.join(dir, entry.name);
    const rel = path.relative(base, abs).split(path.sep).join('/');
    return entry.isDirectory() ? [`${rel}/`, ...tree(abs, base)] : [rel];
  }).sort();
}

const read = (root, rel) => fs.readFileSync(path.join(root, ...rel.split('/')), 'utf8');
const errorOf = (fn) => {
  try {
    fn();
  } catch (error) {
    assert.ok(error instanceof BrainWriterError, `expected BrainWriterError, got ${error?.constructor?.name}: ${error?.message}`);
    return error;
  }
  assert.fail('expected a BrainWriterError');
  return null;
};

function trySymlink(target, linkPath, type) {
  try {
    fs.symlinkSync(target, linkPath, type);
    return true;
  } catch {
    return false;
  }
}

function patchFs(name, replacement) {
  const original = fs[name];
  fs[name] = replacement(original);
  return () => { fs[name] = original; };
}

